import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { LANGS } = await import(pathToFileURL(join(root, 'languages/index.js')).href);
mkdirSync(join(root, 'data/lang'), { recursive: true });

export function serialize(pack) {
  return {
    code: pack.code, name: pack.name, dir: pack.dir,
    days: pack.days, daysShort: pack.daysShort, months: pack.months,
    phrases: pack.phrases || {}, templates: pack.templates || [], words: pack.words || {},
    polish: (pack.polish || []).map(([re, to]) => [re.source, re.flags, to]),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();

async function main() {
const versions = {};
for (const l of LANGS) {
  if (l.code === 'he') continue;
  const pack = l.pack || (l.load ? (await l.load()).default : null);
  if (!pack) continue;
  const body = serialize(pack), hash = createHash('sha256').update(JSON.stringify(body)).digest('hex').slice(0, 16);
  const file = join(root, 'data/lang', `${l.code}.json`);
  const old = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null;
  const version = old?.hash === hash ? old.version : (old?.version || 0) + 1;
  if (old?.hash !== hash) writeFileSync(file, JSON.stringify({ format: 1, version, hash, ...body }) + '\n');
  versions[l.code] = version;
  console.log(`${l.code}: v${version}${old?.hash === hash ? '' : ' (updated)'}`);
}
const vfile = join(root, 'languages/pack-versions.js');
const vsrc = `// Generated by scripts/build-data.mjs: the version of each language pack built into the app.\nexport default ${JSON.stringify(versions)};\n`;
if (!existsSync(vfile) || readFileSync(vfile, 'utf8') !== vsrc) writeFileSync(vfile, vsrc);
}
