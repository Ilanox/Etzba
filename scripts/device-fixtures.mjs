// Writes js/device-fixtures.js: answers worked out here (Node, Israel time) that the phone must reproduce in the
// on-device tests, so a difference in the phone's dates, time zone, calendar or number formatting shows up.
// A unit test checks the file is current; after changing the pay engine or calendar: node scripts/device-fixtures.mjs
import { writeFileSync } from 'node:fs';
import { fromRoot } from './lib.mjs';

process.env.TZ = 'Asia/Jerusalem';
globalThis.addEventListener ??= () => {};
const { shiftPay, defaultJob } = await import('../js/pay-engine.js');
const { holidaysOfGregorianYear, sunset, restWindows } = await import('../js/hebrew-calendar.js');
const { money, hm } = await import('../js/util.js');

export const place = { city: 'תל אביב', candleMin: 18, havdalahMin: 40 };
export const SHIFTS = [
  ['יום חול ארוך', '2026-11-17T08:00:00+02:00', 12],
  ['שישי לתוך שבת', '2026-11-20T09:00:00+02:00', 13],
  ['יום כיפור', '2026-09-21T10:00:00+03:00', 10],
  ['לילה, מעבר שעון חורף', '2026-10-24T22:00:00+03:00', 10],
  ['מוצאי שבת', '2026-11-21T14:00:00+02:00', 9],
];

export function compute() {
  const job = { ...defaultJob('test'), rate: 43.5 };
  const pay = SHIFTS.map(([name, start, hours]) => {
    const p = shiftPay({ start, end: new Date(+new Date(start) + hours * 36e5).toISOString(), breakMin: 0 }, job, place);
    return { name, start, hours, pay: Math.round(p.pay * 100) / 100, minutes: Math.round(p.hours * 60) };
  });
  const holidays = holidaysOfGregorianYear(2026).map(h => [h.name, new Date(h.date).toISOString()]);
  const sun = new Date(sunset(2026, 5, 21, 32.085, 34.781)).toISOString();
  const rest = restWindows(new Date('2026-11-20T00:00:00+02:00'), new Date('2026-11-22T00:00:00+02:00'), place, job)
    .map(w => [new Date(w.from ?? w.start ?? w[0]).toISOString(), new Date(w.to ?? w.end ?? w[1]).toISOString()]);
  return { pay, holidays, sun, rest, money: [money(1234.5), money(98765)], hm: [hm(8.6), hm(12.25)] };
}

if (process.argv[1]?.endsWith('device-fixtures.mjs')) {
  writeFileSync(fromRoot('js/device-fixtures.js'), `// Generated by scripts/device-fixtures.mjs: what the phone must get (see js/device-tests.js).\n/* translations: skip-start (developer only) */\nexport const SHIFTS = ${JSON.stringify(SHIFTS)};\nexport const PLACE = ${JSON.stringify(place)};\nexport const EXPECT = ${JSON.stringify(compute(), null, 1)};\n/* translations: skip-end */\n`);
  console.log('js/device-fixtures.js written');
}
